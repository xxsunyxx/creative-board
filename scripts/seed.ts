import { db } from "../lib/db";
import {
  canvases,
  documents,
  inspirationKeywords,
  inspirations,
} from "../lib/db/schema";

const seedInspirations = [
  {
    title: "远程办公",
    content: "降低通勤成本，但沟通变慢，非正式交流减少。",
    keywords: ["远程办公", "沟通成本", "协作"],
  },
  {
    title: "团队创新",
    content: "需要高频碰撞、心理安全和非正式交流。",
    keywords: ["团队创新", "心理安全", "碰撞"],
  },
  {
    title: "AI 协作工具",
    content: "异步沟通、自动记录、降低协调成本，但可能增加信息噪音。",
    keywords: ["AI 协作", "异步", "信息噪音"],
  },
  {
    title: "组织信任",
    content: "高质量关系提升创新容错，让失败复盘变成学习而不是追责。",
    keywords: ["组织信任", "容错", "复盘"],
  },
];

function main() {
  const existing = db.select().from(canvases).all();
  if (existing.length > 0) {
    console.log("Seed skipped: canvases already exist.");
    return;
  }

  const canvasId = crypto.randomUUID();

  db.insert(canvases)
    .values({
      id: canvasId,
      name: "组织创新",
      description: "远程办公、团队创新与 AI 协作工具之间的关系探索。",
      colorLegend: [
        { color: "#3b82f6", label: "远程办公", autoGenerated: true },
        { color: "#8b5cf6", label: "团队创新", autoGenerated: true },
        { color: "#10b981", label: "AI 工具", autoGenerated: true },
        { color: "#f59e0b", label: "组织信任", autoGenerated: true },
      ],
    })
    .run();

  for (const item of seedInspirations) {
    const inspirationId = crypto.randomUUID();

    db.insert(inspirations)
      .values({
        id: inspirationId,
        title: item.title,
        content: item.content,
        origin: "manual",
        status: "active",
      })
      .run();

    for (const keyword of item.keywords) {
      db.insert(inspirationKeywords)
        .values({
          id: crypto.randomUUID(),
          inspirationId,
          keyword,
        })
        .run();
    }
  }

  db.insert(documents)
    .values({
      id: crypto.randomUUID(),
      title: "远程办公与团队创新",
      content: [
        "# 远程办公与团队创新",
        "",
        "远程办公降低了通勤成本，但也减少了非正式交流。",
        "",
        "## 关键条件",
        "",
        "- 高频同步可能促进创新，但依赖团队规模与工具。",
        "- 组织信任是容错的前提。",
        "",
        "> 这是 M1 的种子文档，后续由输出节点生成。",
      ].join("\n"),
    })
    .run();

  console.log("Seed complete.");
}

main();
