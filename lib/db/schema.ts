import { index, integer, real, sqliteTable, text } from "drizzle-orm/sqlite-core";

export type ColorGroup = {
  color: string;
  label: string;
  autoGenerated?: boolean;
};

function createdAtColumn() {
  return integer("created_at", { mode: "timestamp_ms" })
    .notNull()
    .$defaultFn(() => new Date());
}

function updatedAtColumn() {
  return integer("updated_at", { mode: "timestamp_ms" })
    .notNull()
    .$defaultFn(() => new Date());
}

function timestamps() {
  return {
    createdAt: createdAtColumn(),
    updatedAt: updatedAtColumn(),
  };
}

export const canvases = sqliteTable(
  "canvases",
  {
    id: text("id").primaryKey(),
    name: text("name").notNull(),
    description: text("description").notNull().default(""),
    colorLegend: text("color_legend", { mode: "json" }).$type<ColorGroup[]>(),
    ...timestamps(),
  },
  (table) => [index("canvases_updated_idx").on(table.updatedAt)],
);

export const inspirations = sqliteTable(
  "inspirations",
  {
    id: text("id").primaryKey(),
    title: text("title").notNull(),
    content: text("content").notNull().default(""),
    sourceUrl: text("source_url"),
    origin: text("origin", { enum: ["manual", "merged", "ai"] })
      .notNull()
      .default("manual"),
    status: text("status", { enum: ["active", "merged", "archived"] })
      .notNull()
      .default("active"),
    mergedInto: text("merged_into"),
    ...timestamps(),
  },
  (table) => [index("inspirations_status_idx").on(table.status)],
);

export const inspirationKeywords = sqliteTable(
  "inspiration_keywords",
  {
    id: text("id").primaryKey(),
    inspirationId: text("inspiration_id")
      .notNull()
      .references(() => inspirations.id, { onDelete: "cascade" }),
    keyword: text("keyword").notNull(),
    createdAt: createdAtColumn(),
  },
  (table) => [index("inspiration_keywords_inspiration_idx").on(table.inspirationId)],
);

export const inspirationNotes = sqliteTable(
  "inspiration_notes",
  {
    id: text("id").primaryKey(),
    inspirationId: text("inspiration_id")
      .notNull()
      .references(() => inspirations.id, { onDelete: "cascade" }),
    stickyNoteId: text("sticky_note_id"),
    content: text("content").notNull(),
    createdAt: createdAtColumn(),
  },
  (table) => [index("inspiration_notes_inspiration_idx").on(table.inspirationId)],
);

export const canvasNodes = sqliteTable(
  "canvas_nodes",
  {
    id: text("id").primaryKey(),
    canvasId: text("canvas_id")
      .notNull()
      .references(() => canvases.id, { onDelete: "cascade" }),
    type: text("type", { enum: ["inspiration", "output"] })
      .notNull()
      .default("inspiration"),
    sourceInspirationId: text("source_inspiration_id").references(
      () => inspirations.id,
      { onDelete: "set null" },
    ),
    title: text("title").notNull(),
    content: text("content").notNull().default(""),
    weight: integer("weight").notNull().default(5),
    color: text("color").notNull().default("#3b82f6"),
    note: text("note").notNull().default(""),
    selectedQuestion: text("selected_question"),
    result: text("result"),
    status: text("status", { enum: ["draft", "saved"] })
      .notNull()
      .default("draft"),
    x: real("x").notNull().default(0),
    y: real("y").notNull().default(0),
    width: real("width").notNull().default(240),
    height: real("height").notNull().default(160),
    deletedAt: integer("deleted_at", { mode: "timestamp_ms" }),
    ...timestamps(),
  },
  (table) => [
    index("canvas_nodes_canvas_idx").on(table.canvasId),
    index("canvas_nodes_type_idx").on(table.type),
  ],
);

export const connections = sqliteTable(
  "connections",
  {
    id: text("id").primaryKey(),
    canvasId: text("canvas_id")
      .notNull()
      .references(() => canvases.id, { onDelete: "cascade" }),
    fromNodeId: text("from_node_id")
      .notNull()
      .references(() => canvasNodes.id, { onDelete: "cascade" }),
    toNodeId: text("to_node_id")
      .notNull()
      .references(() => canvasNodes.id, { onDelete: "cascade" }),
    createdAt: createdAtColumn(),
  },
  (table) => [
    index("connections_canvas_idx").on(table.canvasId),
    index("connections_from_idx").on(table.fromNodeId),
    index("connections_to_idx").on(table.toNodeId),
  ],
);

export const dimensionGroups = sqliteTable(
  "dimension_groups",
  {
    id: text("id").primaryKey(),
    connectionId: text("connection_id")
      .notNull()
      .references(() => connections.id, { onDelete: "cascade" }),
    relationType: text("relation_type").notNull(),
    orderIndex: integer("order_index").notNull().default(0),
    attributes: text("attributes", { mode: "json" }).$type<Record<string, unknown>>(),
    createdAt: createdAtColumn(),
  },
  (table) => [index("dimension_groups_connection_idx").on(table.connectionId)],
);

export const dimensionNodes = sqliteTable(
  "dimension_nodes",
  {
    id: text("id").primaryKey(),
    groupId: text("group_id")
      .notNull()
      .references(() => dimensionGroups.id, { onDelete: "cascade" }),
    parentId: text("parent_id"),
    label: text("label").notNull(),
    level: text("level", { enum: ["main", "detail", "deeper"] })
      .notNull()
      .default("main"),
    selected: integer("selected", { mode: "boolean" }).notNull().default(false),
    orderIndex: integer("order_index").notNull().default(0),
    createdAt: createdAtColumn(),
  },
  (table) => [
    index("dimension_nodes_group_idx").on(table.groupId),
    index("dimension_nodes_parent_idx").on(table.parentId),
  ],
);

export const documents = sqliteTable(
  "documents",
  {
    id: text("id").primaryKey(),
    outputNodeId: text("output_node_id").references(() => canvasNodes.id, {
      onDelete: "set null",
    }),
    title: text("title").notNull(),
    content: text("content").notNull().default(""),
    ...timestamps(),
  },
  (table) => [index("documents_output_idx").on(table.outputNodeId)],
);

export const provenanceLinks = sqliteTable(
  "provenance_links",
  {
    id: text("id").primaryKey(),
    outputNodeId: text("output_node_id")
      .notNull()
      .references(() => canvasNodes.id, { onDelete: "cascade" }),
    contextNodeIds: text("context_node_ids", { mode: "json" })
      .$type<string[]>()
      .notNull()
      .default([]),
    contextConnectionIds: text("context_connection_ids", { mode: "json" })
      .$type<string[]>()
      .notNull()
      .default([]),
    createdAt: createdAtColumn(),
  },
  (table) => [index("provenance_links_output_idx").on(table.outputNodeId)],
);

export const generationHistory = sqliteTable(
  "generation_history",
  {
    id: text("id").primaryKey(),
    targetType: text("target_type").notNull(),
    targetId: text("target_id").notNull(),
    kind: text("kind").notNull(),
    candidates: text("candidates", { mode: "json" }).$type<unknown[]>(),
    selected: text("selected"),
    createdAt: createdAtColumn(),
  },
  (table) => [
    index("generation_history_target_idx").on(table.targetType, table.targetId),
  ],
);

export const settings = sqliteTable("settings", {
  key: text("key").primaryKey(),
  value: text("value", { mode: "json" }).$type<unknown>(),
  updatedAt: updatedAtColumn(),
});

export type Canvas = typeof canvases.$inferSelect;
export type Inspiration = typeof inspirations.$inferSelect;
export type InspirationKeyword = typeof inspirationKeywords.$inferSelect;
export type InspirationNote = typeof inspirationNotes.$inferSelect;
export type CanvasNode = typeof canvasNodes.$inferSelect;
export type Connection = typeof connections.$inferSelect;
export type DimensionGroup = typeof dimensionGroups.$inferSelect;
export type DimensionNode = typeof dimensionNodes.$inferSelect;
export type Document = typeof documents.$inferSelect;
export type ProvenanceLink = typeof provenanceLinks.$inferSelect;
export type GenerationHistory = typeof generationHistory.$inferSelect;
